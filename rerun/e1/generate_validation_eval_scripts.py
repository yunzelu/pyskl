"""Generate E1 validation-subject inference configs and SLURM jobs.

The generated jobs evaluate already-selected checkpoints on each fold's
validation subject. A2 reuses the A1 checkpoint and evaluates it on continuous
windows. B and C use their own validation-selected checkpoints.
"""

from __future__ import annotations

import argparse
import json
from dataclasses import dataclass
from pathlib import Path
from typing import Any


FOLDS = ["a", "b", "c"]
STREAMS = ["joint", "bone"]

DEFAULT_CONFIG_ROOT = Path("configs/stgcn++/stgcn++_radarv4/rerun/e1")
DEFAULT_JOB_ROOT = Path("rerun/e1/slurm")
DEFAULT_WORK_ROOT = Path("work_dirs/rerun/e1")
DEFAULT_REPORT_PATH = Path("rerun/e1/generated_validation_eval_scripts.json")


@dataclass(frozen=True)
class ValidationCondition:
    key: str
    result_dir: str
    base_config_name: str
    checkpoint_result_dir: str


CONDITIONS = [
    ValidationCondition(
        key="a1",
        result_dir="a1_activity_aligned",
        base_config_name="a1_activity_aligned.py",
        checkpoint_result_dir="a1_activity_aligned",
    ),
    ValidationCondition(
        key="a2",
        result_dir="a2_activity_checkpoint_on_continuous",
        base_config_name="b_continuous_window.py",
        checkpoint_result_dir="a1_activity_aligned",
    ),
    ValidationCondition(
        key="b",
        result_dir="b_continuous_window",
        base_config_name="b_continuous_window.py",
        checkpoint_result_dir="b_continuous_window",
    ),
    ValidationCondition(
        key="c",
        result_dir="c_triangular_temporal_composition",
        base_config_name="c_triangular_temporal_composition.py",
        checkpoint_result_dir="c_triangular_temporal_composition",
    ),
]


def write_text(path: Path, text: str, overwrite: bool) -> None:
    if path.exists() and not overwrite:
        raise FileExistsError(f"{path} exists; pass --overwrite to replace it.")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")


def validation_config_text(
    base_config_path: Path,
    work_dir: Path,
    condition: ValidationCondition,
) -> str:
    base_text = base_config_path.read_text(encoding="utf-8")
    return (
        "# ============================================================\n"
        f"# Rerun E1 validation-subject evaluation: {condition.key.upper()}\n"
        f"# Base config: {base_config_path.as_posix()}\n"
        "# Generated by rerun/e1/generate_validation_eval_scripts.py\n"
        "# ============================================================\n\n"
        + base_text
        + "\n\n"
        + "# Validation-subject inference override.\n"
        + f"work_dir = {work_dir.as_posix()!r}\n"
        + "data['test'] = dict(data['val'])\n"
        + "test_evaluation = dict(\n"
        + "    metrics=['top_k_accuracy', 'macro_f1'],\n"
        + "    metric_options=dict(top_k_accuracy=dict(topk=(1,)))\n"
        + ")\n"
    )


def slurm_header(fold: str, stream: str, time_limit: str) -> str:
    return f"""#!/bin/bash
#SBATCH --account=def-mbolic
#SBATCH --gpus-per-node=a100:4
#SBATCH --cpus-per-task=12
#SBATCH --mem=62G
#SBATCH --time={time_limit}
#SBATCH --job-name=e1_val_fold_{fold}_{stream}
#SBATCH --output=rerun/e1/slurm/%x_%j.out
#SBATCH --mail-user=yunzelu@outlook.com
#SBATCH --mail-type=BEGIN,END,FAIL

set -euo pipefail

module purge
module load StdEnv/2020 gcc/9.3.0 cuda/11.8 python/3.10 opencv/4.5.5
source ~/projects/def-mbolic/yunzelu/pyskl/.venv/bin/activate
cd ~/projects/def-mbolic/yunzelu/pyskl/

GPUS="${{GPUS:-4}}"
FOLD="{fold}"
STREAM="{stream}"
CONFIG_ROOT="configs/stgcn++/stgcn++_radarv4/rerun/e1/fold_${{FOLD}}/${{STREAM}}/validation"
WORK_ROOT="work_dirs/rerun/e1/fold_${{FOLD}}"

find_best_checkpoint() {{
  local work_dir="$1"
  mapfile -t ckpts < <(find "${{work_dir}}" -maxdepth 1 -name 'best_macro_f1_epoch_*.pth' | sort -V)
  if [[ "${{#ckpts[@]}}" -ne 1 ]]; then
    echo "[ERROR] Expected one best_macro_f1 checkpoint in ${{work_dir}}, found ${{#ckpts[@]}}" >&2
    printf '%s\\n' "${{ckpts[@]}}" >&2
    exit 1
  fi
  printf '%s\\n' "${{ckpts[0]}}"
}}

run_validation_eval() {{
  local condition_key="$1"
  local config_name="$2"
  local checkpoint_condition_dir="$3"
  local result_condition_dir="$4"

  local ckpt_dir="${{WORK_ROOT}}/${{STREAM}}/${{checkpoint_condition_dir}}"
  local ckpt
  ckpt="$(find_best_checkpoint "${{ckpt_dir}}")"
  local out_dir="${{WORK_ROOT}}/${{STREAM}}/${{result_condition_dir}}/validation"
  mkdir -p "${{out_dir}}"

  echo "[INFO] fold=${{FOLD}} stream=${{STREAM}} condition=${{condition_key}} checkpoint=${{ckpt}}"
  bash tools/dist_test.sh "${{CONFIG_ROOT}}/${{config_name}}" "${{ckpt}}" "${{GPUS}}" \\
    --out "${{out_dir}}/best_pred.pkl" \\
    --eval-out "${{out_dir}}/best_eval.json"
}}
"""


def validation_job_text(fold: str, stream: str) -> str:
    lines = [slurm_header(fold, stream, "02:00:00")]
    for condition in CONDITIONS:
        lines.append(
            "run_validation_eval "
            f"{condition.key!r} "
            f"{condition.key + '_validation.py'!r} "
            f"{condition.checkpoint_result_dir!r} "
            f"{condition.result_dir!r}"
        )
    lines.append("")
    return "\n".join(lines)


def generate(
    folds: list[str],
    streams: list[str],
    config_root: Path,
    job_root: Path,
    work_root: Path,
    report_path: Path,
    overwrite: bool,
) -> None:
    outputs: dict[str, Any] = {"configs": [], "jobs": [], "folds": {}}

    for fold in folds:
        if fold not in FOLDS:
            raise ValueError(f"Unknown fold {fold!r}; expected one of {FOLDS}")
        outputs["folds"][fold] = {}
        for stream in streams:
            if stream not in STREAMS:
                raise ValueError(f"Unknown stream {stream!r}; expected one of {STREAMS}")

            stream_dir = config_root / f"fold_{fold}" / stream
            validation_config_dir = stream_dir / "validation"
            outputs["folds"][fold][stream] = []
            for condition in CONDITIONS:
                base_config_path = stream_dir / condition.base_config_name
                if not base_config_path.exists():
                    raise FileNotFoundError(base_config_path)

                validation_work_dir = (
                    work_root
                    / f"fold_{fold}"
                    / stream
                    / condition.result_dir
                    / "validation"
                )
                validation_config_path = (
                    validation_config_dir / f"{condition.key}_validation.py"
                )
                write_text(
                    validation_config_path,
                    validation_config_text(
                        base_config_path=base_config_path,
                        work_dir=validation_work_dir,
                        condition=condition,
                    ),
                    overwrite=overwrite,
                )
                outputs["configs"].append(str(validation_config_path))
                outputs["folds"][fold][stream].append(
                    {
                        "condition": condition.key,
                        "config": str(validation_config_path),
                        "checkpoint_result_dir": condition.checkpoint_result_dir,
                        "output_result_dir": str(validation_work_dir),
                    }
                )

            job_path = job_root / f"run_validation_fold_{fold}_{stream}.sh"
            write_text(job_path, validation_job_text(fold, stream), overwrite=overwrite)
            outputs["jobs"].append(str(job_path))

    report_path.parent.mkdir(parents=True, exist_ok=True)
    report_path.write_text(
        json.dumps(outputs, indent=2, ensure_ascii=False) + "\n",
        encoding="utf-8",
        newline="\n",
    )


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--folds", nargs="+", default=FOLDS)
    parser.add_argument("--streams", nargs="+", default=STREAMS)
    parser.add_argument("--config-root", type=Path, default=DEFAULT_CONFIG_ROOT)
    parser.add_argument("--job-root", type=Path, default=DEFAULT_JOB_ROOT)
    parser.add_argument("--work-root", type=Path, default=DEFAULT_WORK_ROOT)
    parser.add_argument("--report-path", type=Path, default=DEFAULT_REPORT_PATH)
    parser.add_argument("--overwrite", action="store_true")
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    generate(
        folds=[fold.lower() for fold in args.folds],
        streams=[stream.lower() for stream in args.streams],
        config_root=args.config_root,
        job_root=args.job_root,
        work_root=args.work_root,
        report_path=args.report_path,
        overwrite=args.overwrite,
    )
    print(f"[DONE] wrote validation eval configs under {args.config_root}")
    print(f"[DONE] wrote validation eval SLURM jobs under {args.job_root}")
    print(f"[DONE] wrote generation report to {args.report_path}")


if __name__ == "__main__":
    main()
