"""Summarize E1 validation-subject single-stream and fusion results.

Run this after the validation inference jobs generated by
``generate_validation_eval_scripts.py`` finish. Metrics are averaged across
the three folds with equal fold weight.
"""

from __future__ import annotations

import argparse
import csv
import importlib
import json
import pickle
import sys
from collections import defaultdict
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import numpy as np


LABELS = [
    "lie-stationary",
    "sit-stationary",
    "walk",
    "fall",
    "transition-lie-to-sit",
    "transition-lie-to-stand",
    "transition-sit-to-lie",
    "transition-sit-to-stand",
    "transition-stand-to-sit",
]
FOLDS = ["a", "b", "c"]
STREAMS = ["joint", "bone"]


@dataclass(frozen=True)
class Condition:
    key: str
    result_dir: str
    pkl_protocol_dir: str
    pkl_stem: str
    checkpoint_result_dir: str


CONDITIONS = [
    Condition(
        key="a1",
        result_dir="a1_activity_aligned",
        pkl_protocol_dir="activity_aligned",
        pkl_stem="radarv4_yolo26xpose_activity_aligned_fold_{fold}.pkl",
        checkpoint_result_dir="a1_activity_aligned",
    ),
    Condition(
        key="a2",
        result_dir="a2_activity_checkpoint_on_continuous",
        pkl_protocol_dir="continuous_window_w60_s12",
        pkl_stem="radarv4_yolo26xpose_continuous_window_w60_s12_fold_{fold}.pkl",
        checkpoint_result_dir="a1_activity_aligned",
    ),
    Condition(
        key="b",
        result_dir="b_continuous_window",
        pkl_protocol_dir="continuous_window_w60_s12",
        pkl_stem="radarv4_yolo26xpose_continuous_window_w60_s12_fold_{fold}.pkl",
        checkpoint_result_dir="b_continuous_window",
    ),
    Condition(
        key="c",
        result_dir="c_triangular_temporal_composition",
        pkl_protocol_dir="continuous_window_w60_s12_triangular",
        pkl_stem="radarv4_yolo26xpose_continuous_window_w60_s12_triangular_fold_{fold}.pkl",
        checkpoint_result_dir="c_triangular_temporal_composition",
    ),
]


def install_numpy_pickle_compat_aliases() -> None:
    """Allow NumPy 2-generated pkls to load under NumPy 1.x."""

    try:
        importlib.import_module("numpy._core.numeric")
        return
    except ModuleNotFoundError:
        pass

    aliases = {
        "numpy._core": "numpy.core",
        "numpy._core.numeric": "numpy.core.numeric",
        "numpy._core.multiarray": "numpy.core.multiarray",
        "numpy._core._multiarray_umath": "numpy.core._multiarray_umath",
    }
    for alias, target in aliases.items():
        try:
            sys.modules.setdefault(alias, importlib.import_module(target))
        except ModuleNotFoundError:
            continue


def load_pickle(path: Path) -> Any:
    install_numpy_pickle_compat_aliases()
    with path.open("rb") as f:
        return pickle.load(f)


def load_json(path: Path) -> dict[str, Any]:
    with path.open("r", encoding="utf-8") as f:
        return json.load(f)


def write_json(path: Path, payload: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as f:
        json.dump(payload, f, indent=2, ensure_ascii=False)
        f.write("\n")


def write_csv(path: Path, rows: list[dict[str, Any]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if not rows:
        raise ValueError(f"No rows to write for {path}")
    fieldnames = sorted({key for row in rows for key in row})
    with path.open("w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)


def pkl_path(data_root: Path, condition: Condition, fold: str) -> Path:
    return data_root / condition.pkl_protocol_dir / condition.pkl_stem.format(fold=fold)


def split_annotations(pkl_file: Path, split_name: str = "val") -> list[dict[str, Any]]:
    data = load_pickle(pkl_file)
    annotations = data["annotations"]
    identifier = "filename" if "filename" in annotations[0] else "frame_dir"
    split_ids = set(data["split"][split_name])
    return [item for item in annotations if item[identifier] in split_ids]


def load_labels(pkl_file: Path, split_name: str = "val") -> np.ndarray:
    annotations = split_annotations(pkl_file, split_name)
    return np.array([int(item["label"]) for item in annotations], dtype=np.int64)


def load_scores(path: Path) -> np.ndarray:
    scores = np.asarray(load_pickle(path), dtype=np.float64)
    if scores.ndim != 2:
        raise ValueError(f"Expected 2D score array in {path}, got {scores.shape}")
    if scores.shape[1] != len(LABELS):
        raise ValueError(f"Expected {len(LABELS)} classes in {path}, got {scores.shape[1]}")
    return scores


def scores_to_probabilities(scores: np.ndarray) -> tuple[np.ndarray, str]:
    row_sums = scores.sum(axis=1)
    if (
        np.all(scores >= -1e-6)
        and np.all(scores <= 1.0 + 1e-6)
        and np.allclose(row_sums, 1.0, atol=1e-4)
    ):
        return scores, "already_probabilities"

    stable = scores - scores.max(axis=1, keepdims=True)
    exp_scores = np.exp(stable)
    return exp_scores / exp_scores.sum(axis=1, keepdims=True), "softmax_applied"


def metric_dict(scores: np.ndarray, labels: np.ndarray) -> dict[str, float]:
    predictions = np.argmax(scores, axis=1).astype(np.int64)
    top1 = float(np.mean(predictions == labels))
    num_classes = scores.shape[1]
    confusion = np.bincount(
        num_classes * labels + predictions,
        minlength=num_classes * num_classes,
    ).reshape(num_classes, num_classes).astype(np.float64)
    tp = np.diag(confusion)
    pred_count = confusion.sum(axis=0)
    true_count = confusion.sum(axis=1)
    precision = np.divide(tp, pred_count, out=np.zeros_like(tp), where=pred_count != 0)
    recall = np.divide(tp, true_count, out=np.zeros_like(tp), where=true_count != 0)
    denom = precision + recall
    f1 = np.divide(2 * precision * recall, denom, out=np.zeros_like(tp), where=denom != 0)
    return {"top1_acc": top1, "macro_f1": float(np.mean(f1))}


def validation_result_paths(
    work_root: Path,
    fold: str,
    stream: str,
    condition: Condition,
) -> tuple[Path, Path]:
    base = work_root / f"fold_{fold}" / stream / condition.result_dir / "validation"
    return base / "best_pred.pkl", base / "best_eval.json"


def find_selected_checkpoint(
    work_root: Path,
    fold: str,
    stream: str,
    condition: Condition,
) -> Path:
    checkpoint_dir = (
        work_root
        / f"fold_{fold}"
        / stream
        / condition.checkpoint_result_dir
    )
    checkpoints = sorted(checkpoint_dir.glob("best_macro_f1_epoch_*.pth"))
    if len(checkpoints) != 1:
        raise FileNotFoundError(
            f"Expected one selected checkpoint in {checkpoint_dir}, "
            f"found {len(checkpoints)}."
        )
    return checkpoints[0]


def active_conditions(work_root: Path) -> list[Condition]:
    active: list[Condition] = []
    expected_count = len(FOLDS) * len(STREAMS)
    for condition in CONDITIONS:
        pred_paths = [
            validation_result_paths(work_root, fold, stream, condition)[0]
            for fold in FOLDS
            for stream in STREAMS
        ]
        existing_count = sum(path.exists() for path in pred_paths)
        if existing_count == 0:
            continue
        if existing_count != expected_count:
            missing = [str(path) for path in pred_paths if not path.exists()]
            raise FileNotFoundError(
                f"Partial validation predictions for {condition.key}: "
                f"{existing_count}/{expected_count} best_pred.pkl files found. "
                f"Missing examples: {missing[:3]}"
            )
        active.append(condition)
    return active


def add_single_stream_rows(
    rows: list[dict[str, Any]],
    work_root: Path,
    data_root: Path,
    fold: str,
    condition: Condition,
) -> dict[str, np.ndarray]:
    labels = load_labels(pkl_path(data_root, condition, fold), "val")
    score_by_stream: dict[str, np.ndarray] = {}
    for stream in STREAMS:
        pred_path, eval_path = validation_result_paths(work_root, fold, stream, condition)
        scores = load_scores(pred_path)
        probabilities, score_format = scores_to_probabilities(scores)
        if len(probabilities) != len(labels):
            raise ValueError(
                f"{pred_path} has {len(probabilities)} predictions, expected {len(labels)}"
            )
        metrics = metric_dict(probabilities, labels)
        eval_metrics = load_json(eval_path) if eval_path.exists() else {}
        for key, value in metrics.items():
            if key in eval_metrics and abs(float(eval_metrics[key]) - value) > 1e-6:
                raise ValueError(
                    f"{eval_path} {key}={eval_metrics[key]} does not match "
                    f"recomputed {value}"
                )

        selected_checkpoint = find_selected_checkpoint(work_root, fold, stream, condition)
        rows.append(
            {
                "condition": condition.key,
                "fold": fold,
                "split": "val",
                "stream": stream,
                "num_samples": len(labels),
                "score_format": score_format,
                "selected_checkpoint": str(selected_checkpoint),
                **metrics,
            }
        )
        score_by_stream[stream] = probabilities
    return score_by_stream


def add_fusion_row(
    rows: list[dict[str, Any]],
    work_root: Path,
    data_root: Path,
    fold: str,
    condition: Condition,
    score_by_stream: dict[str, np.ndarray],
    write_predictions: bool,
) -> None:
    labels = load_labels(pkl_path(data_root, condition, fold), "val")
    joint = score_by_stream["joint"]
    bone = score_by_stream["bone"]
    if joint.shape != bone.shape:
        raise ValueError(f"Joint/bone shape mismatch for {condition.key} fold {fold}")

    fusion_scores = 0.5 * (joint + bone)
    metrics = metric_dict(fusion_scores, labels)
    joint_ckpt = find_selected_checkpoint(work_root, fold, "joint", condition)
    bone_ckpt = find_selected_checkpoint(work_root, fold, "bone", condition)

    fusion_dir = work_root / f"fold_{fold}" / "fusion" / condition.result_dir / "validation"
    if write_predictions:
        fusion_dir.mkdir(parents=True, exist_ok=True)
        with (fusion_dir / "best_pred.pkl").open("wb") as f:
            pickle.dump(
                fusion_scores.astype(np.float32).tolist(),
                f,
                protocol=pickle.HIGHEST_PROTOCOL,
            )
        write_json(
            fusion_dir / "best_eval.json",
            {
                **metrics,
                "split": "val",
                "fusion_rule": "0.5 * (joint_probability + bone_probability)",
                "num_samples": len(labels),
                "joint_checkpoint": str(joint_ckpt),
                "bone_checkpoint": str(bone_ckpt),
                "source_order": "PYSKL PoseDataset val order",
            },
        )

    rows.append(
        {
            "condition": condition.key,
            "fold": fold,
            "split": "val",
            "stream": "fusion",
            "num_samples": len(labels),
            "score_format": "mean_joint_bone_probabilities",
            "joint_checkpoint": str(joint_ckpt),
            "bone_checkpoint": str(bone_ckpt),
            **metrics,
        }
    )


def aggregate_rows(rows: list[dict[str, Any]]) -> list[dict[str, Any]]:
    grouped: dict[tuple[str, str], list[dict[str, Any]]] = defaultdict(list)
    for row in rows:
        grouped[(str(row["condition"]), str(row["stream"]))].append(row)

    summary_rows: list[dict[str, Any]] = []
    present_conditions = [
        condition.key
        for condition in CONDITIONS
        if any(str(row["condition"]) == condition.key for row in rows)
    ]
    for condition in present_conditions:
        for stream in [*STREAMS, "fusion"]:
            fold_rows = grouped[(condition, stream)]
            if len(fold_rows) != len(FOLDS):
                raise ValueError(
                    f"Expected {len(FOLDS)} folds for {condition}/{stream}, "
                    f"found {len(fold_rows)}"
                )
            top1 = np.array([float(row["top1_acc"]) for row in fold_rows])
            macro_f1 = np.array([float(row["macro_f1"]) for row in fold_rows])
            summary_rows.append(
                {
                    "condition": condition,
                    "stream": stream,
                    "folds": len(fold_rows),
                    "top1_acc_mean": float(np.mean(top1)),
                    "top1_acc_sd": float(np.std(top1, ddof=1)),
                    "macro_f1_mean": float(np.mean(macro_f1)),
                    "macro_f1_sd": float(np.std(macro_f1, ddof=1)),
                }
            )
    return summary_rows


def format_mean_sd(mean: float, sd: float) -> str:
    return f"{mean:.4f} +- {sd:.4f}"


def markdown_report(rows: list[dict[str, Any]], summary_rows: list[dict[str, Any]]) -> str:
    lines = [
        "# E1 Validation-Subject Summary",
        "",
        "These metrics use each method's checkpoint selected by that fold's",
        "validation macro-F1. A2 uses the A1 checkpoint and evaluates it on the",
        "continuous-window validation split. Fusion uses equal-weight averaging",
        "of joint and bone probability distributions.",
        "",
        "## Mean +- SD Across Folds",
        "",
        "| Condition | Stream | Top-1 Acc | Macro F1 |",
        "| --- | --- | ---: | ---: |",
    ]
    for row in summary_rows:
        lines.append(
            "| {condition} | {stream} | {top1} | {f1} |".format(
                condition=str(row["condition"]).upper(),
                stream=row["stream"],
                top1=format_mean_sd(row["top1_acc_mean"], row["top1_acc_sd"]),
                f1=format_mean_sd(row["macro_f1_mean"], row["macro_f1_sd"]),
            )
        )

    lines.extend(
        [
            "",
            "## Fold Metrics",
            "",
            "| Condition | Fold | Stream | N | Top-1 Acc | Macro F1 |",
            "| --- | --- | --- | ---: | ---: | ---: |",
        ]
    )
    for row in rows:
        lines.append(
            "| {condition} | {fold} | {stream} | {n} | {top1:.4f} | {f1:.4f} |".format(
                condition=str(row["condition"]).upper(),
                fold=str(row["fold"]).upper(),
                stream=row["stream"],
                n=int(row["num_samples"]),
                top1=float(row["top1_acc"]),
                f1=float(row["macro_f1"]),
            )
        )
    return "\n".join(lines) + "\n"


def summarize(args: argparse.Namespace) -> None:
    conditions = active_conditions(args.work_root)
    if not conditions:
        raise FileNotFoundError(
            f"No validation best_pred.pkl files found under {args.work_root}. "
            "Run rerun/e1/slurm/run_validation_fold_<fold>_<stream>.sh first."
        )

    rows: list[dict[str, Any]] = []
    for condition in conditions:
        for fold in FOLDS:
            score_by_stream = add_single_stream_rows(
                rows=rows,
                work_root=args.work_root,
                data_root=args.data_root,
                fold=fold,
                condition=condition,
            )
            add_fusion_row(
                rows=rows,
                work_root=args.work_root,
                data_root=args.data_root,
                fold=fold,
                condition=condition,
                score_by_stream=score_by_stream,
                write_predictions=not args.no_write_fusion_predictions,
            )

    summary_rows = aggregate_rows(rows)
    write_csv(args.output_dir / "e1_validation_fold_metrics.csv", rows)
    write_csv(args.output_dir / "e1_validation_mean_sd.csv", summary_rows)
    write_json(
        args.output_dir / "e1_validation_summary.json",
        {
            "split": "val",
            "fold_weighting": "equal_weight_per_fold",
            "fold_metrics": rows,
            "mean_sd": summary_rows,
        },
    )
    (args.output_dir / "e1_validation_summary.md").write_text(
        markdown_report(rows, summary_rows),
        encoding="utf-8",
        newline="\n",
    )


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--work-root", type=Path, default=Path("work_dirs/rerun/e1"))
    parser.add_argument(
        "--data-root",
        type=Path,
        default=Path("data/radar_v4/rerun/yolo26xpose/pyskl"),
    )
    parser.add_argument("--output-dir", type=Path, default=Path("rerun/e1/reports"))
    parser.add_argument(
        "--no-write-fusion-predictions",
        action="store_true",
        help="Do not write fusion best_pred.pkl/best_eval.json under work_root.",
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    try:
        summarize(args)
    except FileNotFoundError as exc:
        print(f"[ERROR] {exc}", file=sys.stderr)
        raise SystemExit(1) from exc
    print(f"[DONE] wrote E1 validation reports under {args.output_dir}")


if __name__ == "__main__":
    main()
